from pathlib import Path
from typing import Literal
from pydantic_settings import BaseSettings, SettingsConfigDict

class Settings(BaseSettings):
    model_config = SettingsConfigDict(
        env_file=".env",
        env_file_encoding="utf-8",
        extra="ignore"
    )

    APP_NAME: str = "freco"
    LOG_LEVEL: str = "INFO"
    # Comma-separated browser origins allowed to call FreCo directly.
    CORS_ALLOWED_ORIGINS: str = "http://localhost:5173"

    @property
    def cors_origins(self) -> list[str]:
        return [origin.strip() for origin in self.CORS_ALLOWED_ORIGINS.split(",") if origin.strip()]

    # --- Hardware ---
    INFERENCE_DEVICE: str = "auto"
    DETECTION_CTX_ID: int = 0

    # --- Face Model Packs ---
    FACE_MODEL_PACK: str = "antelopev2"
    RECOGNITION_MODEL_PACK: str = "antelopev2"
    INSIGHTFACE_MODEL_ROOT: str = "."
    MODEL_ROOT: str = "./models"

    # --- Detection parameters ---
    DETECTION_MIN_CONFIDENCE: float = 0.6

    # --- Request limits ---
    MAX_UPLOAD_IMAGE_MB: int = 5
    MAX_IMAGE_PIXELS: int = 20_000_000
    MAX_CANDIDATE_EMBEDDINGS: int = 1_000

    # Both variants are generated by default; comparisons use matching variants only.
    IMAGE_STORAGE_MODE: Literal["grayscale", "color", "both"] = "grayscale"

    # --- Face Visibility parameters ---
    FACE_VISIBILITY_THRESHOLD: float = 0.8
    FACE_VISIBILITY_FRAME_MARGIN_RATIO: float = 0.05
    FACE_VISIBILITY_MIN_LANDMARK_SPREAD_RATIO: float = 0.1
    FACE_VISIBILITY_EYE_DARK_PIXEL_RATIO: float = 0.1
    FACE_VISIBILITY_NOSE_DARK_PIXEL_RATIO: float = 0.1
    FACE_VISIBILITY_MOUTH_DARK_PIXEL_RATIO: float = 0.1

    # --- Liveness parameters ---
    LIVENESS_MODEL_PATHS: str = "models/liveness/MiniFASNetV2.onnx,models/liveness/MiniFASNetV1SE.onnx"
    LIVENESS_MODEL_SCALES: str = "2.7,4.0"
    LIVENESS_REAL_CLASS_INDEX: int = 1
    LIVENESS_THRESHOLD: float = 0.85

    # --- Similarity parameters ---
    COSINE_SIMILARITY_THRESHOLD: float = 0.55

    @property
    def model_root_path(self) -> Path:
        return Path(self.MODEL_ROOT).resolve()

settings = Settings()
